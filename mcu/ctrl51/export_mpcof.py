#!/usr/bin/env python3
"""CTRL-51: export the MPCOF cascade teacher's OFFLINE tables for the on-board C port
(mcu/mpcof_cascade.c) and record the Rust teacher's reference episodes.

Nothing here computes control: every number comes from the Rust teacher itself.
  1. copy the controller workspace (core + controller, repo read-only) to --work;
  2. add mcu/ctrl51/ctrl51_export.rs to the COPY as a #[cfg(test)] module and run it
     (cargo test --release --no-default-features): it builds the per-axis condensed
     QP (H, g_map, ustar_map) and DARE terminal cost with the teacher's own
     outer_map / dare_doubling / condense_horizon, and flies the cascade teacher on
     cf21_brushless (lag 0.20, L4C, stage 2) recording per-tick inputs + labels;
  3. render mcu/mpcof_model.h from the tables (every f64 as an exact hex literal).

Usage:  python mcu/ctrl51/export_mpcof.py [--work /tmp/ctrl51] [--out mcu/mpcof_model.h]
"""

import argparse
import os
import shutil
import struct
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ACCEL = REPO / "src/wnn/ram/strategies/accelerator"
PYO3 = "/Volumes/20260401-WDBlack-SN850X-2TB/wnn/venv/bin/python"


def copy_workspace(rs: Path):
	"""core + controller + lockfile into a private workspace; the export module added."""
	if rs.exists():
		for sub in ("core", "controller"):
			shutil.rmtree(rs / sub, ignore_errors=True)
	rs.mkdir(parents=True, exist_ok=True)
	ignore = shutil.ignore_patterns("target")
	for sub in ("core", "controller"):
		shutil.copytree(ACCEL / sub, rs / sub, ignore=ignore)
	shutil.copy(ACCEL / "Cargo.lock", rs / "Cargo.lock")
	(rs / "Cargo.toml").write_text('[workspace]\nmembers = ["core", "controller"]\nresolver = "2"\n')
	shutil.copy(Path(__file__).with_name("ctrl51_export.rs"), rs / "controller/ctrl51_export.rs")
	with open(rs / "controller/lib.rs", "a") as f:
		f.write("\n#[cfg(test)]\nmod ctrl51_export; // CTRL-51 /tmp-only reference export\n")


def run_reference(rs: Path, ref: Path):
	ref.mkdir(parents=True, exist_ok=True)
	env = dict(os.environ, CARGO_TARGET_DIR=str(rs / "target"), PYO3_PYTHON=PYO3, CTRL51_OUT=str(ref))
	cmd = ["cargo", "test", "--release", "-p", "ram_controller", "--lib", "--no-default-features",
	       "ctrl51_export", "--", "--nocapture"]
	subprocess.run(cmd, cwd=rs, env=env, check=True)


def parse_tables(path: Path) -> dict:
	"""tables.txt: `key n bits...` (f64 bits in hex) or `key int`."""
	out = {}
	for line in path.read_text().splitlines():
		parts = line.split()
		if len(parts) == 2:
			out[parts[0]] = int(parts[1])
			continue
		n = int(parts[1])
		out[parts[0]] = [struct.unpack("<d", bytes.fromhex(h)[::-1])[0] for h in parts[2:2 + n]]
	return out


def lit(x: float) -> str:
	return f"({float(x).hex()})"


def braced(vals) -> str:
	"""A (nested) list as a C initializer, four literals per line at the leaves."""
	if isinstance(vals[0], list):
		return "{\n" + ",\n".join(braced(v) for v in vals) + "\n}"
	return "{\n\t" + ",\n\t".join(", ".join(lit(v) for v in vals[i:i + 4]) for i in range(0, len(vals), 4)) + "\n}"


def arr(name: str, ctype: str, dims: str, vals) -> str:
	return f"static const {ctype} {name}{dims} = {braced(vals)};"


def per_phase(t: dict, key: str, dec: int) -> list:
	"""[phase][axis][row-major matrix]."""
	return [[t[f"{key}_{ph}_{a}"] for a in range(3)] for ph in range(dec)]


def render(t: dict, source: str) -> str:
	dec, n, ns = t["decimation"], t["horizon"], t["ns"]
	macros = [
		f"#define MPCOF_N_O {t['n_o']}", f"#define MPCOF_HORIZON {n}", f"#define MPCOF_NS {ns}",
		f"#define MPCOF_DECIMATION {dec}", f"#define MPCOF_OBS_KT {lit(t['obs_kt'][0])}",
		f"#define MPCOF_OBS_DT {lit(t['obs_dt'][0])}", f"#define MPCOF_OBS_ALPHA {lit(t['obs_alpha'][0])}",
		f"#define MPCOF_OBS_L {lit(t['obs_l'][0])}", f"#define MPCOF_RATE_OUT_LIMIT {lit(t['rate_out_limit'][0])}",
		f"#define MPCOF_RATE_DT {lit(t['rate_dt'][0])}", f"#define MPCOF_RATE_HAS_LPF {int(t['rate_has_lpf'][0])}",
	]
	tables = [
		arr("mpcof_H", "mpc_real", f"[{dec}][3][{n * n}]", per_phase(t, "H", dec)),
		arr("mpcof_G", "mpc_real", f"[{dec}][3][{n * ns}]", per_phase(t, "G", dec)),
		arr("mpcof_U", "mpc_real", f"[{dec}][3][{n * ns}]", per_phase(t, "U", dec)),
		*(arr(f"mpcof_{k}", "mpc_real", "[3]", t[k]) for k in ("rate_max", "kp", "ki", "c")),
		arr("mpcof_obs_c", "double", "[3]", t["obs_c"]), arr("mpcof_obs_clamp", "double", "[3]", t["obs_clamp"]),
		arr("mpcof_rate_gains", "double", "[12]", t["rate_gains"]), arr("mpcof_rate_lpf", "double", "[5]", t["rate_lpf"]),
	]
	return "\n".join([
		"/* GENERATED by mcu/ctrl51/export_mpcof.py -- do not edit. */",
		f"/* source: {source} */",
		"#ifndef MPCOF_MODEL_H_MACROS", "#define MPCOF_MODEL_H_MACROS", *macros, "#endif", "",
		"#if !defined(MPCOF_MODEL_MACROS_ONLY) && !defined(MPCOF_MODEL_H_TABLES)",
		"#define MPCOF_MODEL_H_TABLES", *tables, "#endif",
	]) + "\n"


def main():
	ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
	ap.add_argument("--work", type=Path, default=Path("/tmp/ctrl51"))
	ap.add_argument("--out", type=Path, default=REPO / "mcu/mpcof_model.h")
	ap.add_argument("--skip-build", action="store_true", help="reuse --work/ref (already exported)")
	a = ap.parse_args()
	ref = a.work / "ref"
	if not a.skip_build:
		copy_workspace(a.work / "rs")
		run_reference(a.work / "rs", ref)
	src = "ram_controller ctbr_mpcof.rs @ ABI 49 (cf21_brushless, lag 0.20, n_o 10)"
	a.out.write_text(render(parse_tables(ref / "tables.txt"), src))
	print(f"wrote {a.out}; reference episodes in {ref}")


if __name__ == "__main__":
	main()
