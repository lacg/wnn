#!/usr/bin/env python3
"""Query header for mcu/bench_pef_replay.c: the first --ticks DECISION ticks of a
recorded VAL address trace (logs/compression_probe/ctrl_addr_trace.py output,
addr[tick, neuron]; the controller decides every 10th tick of each episode, as in
logs/compression_probe/analyze.py), as q_addr[Q_TICKS * WNN_NEURONS].

  python mcu/pef_replay_queries.py --trace <ctrl_trace_<tag>_u<unit>.npz> --out /tmp/q.h [--ticks 200]
"""

import argparse

import numpy as np

DECISION_EVERY = 10


def parse_args():
	ap = argparse.ArgumentParser(description="query header for bench_pef_replay.c")
	ap.add_argument("--trace", required=True)
	ap.add_argument("--out", required=True)
	ap.add_argument("--ticks", type=int, default=200)
	return ap.parse_args()


def decision_rows(addr: np.ndarray, ep_len: np.ndarray, ticks: int) -> np.ndarray:
	t_in = np.concatenate([np.arange(l) for l in ep_len])
	rows = addr[(t_in % DECISION_EVERY) == 0][:ticks]
	if len(rows) < ticks:
		raise SystemExit(f"trace has only {len(rows)} decision ticks < {ticks}")
	return rows.astype(np.uint32)


def render(rows: np.ndarray, source: str) -> str:
	flat = rows.ravel()
	body = ",\n".join("\t" + ", ".join(f"{v}u" for v in flat[i:i + 12]) for i in range(0, len(flat), 12))
	return (f"/* GENERATED by mcu/pef_replay_queries.py from {source} */\n"
	        f"#define Q_TICKS {rows.shape[0]}u\n#define Q_NEURONS {rows.shape[1]}u\n"
	        f"static const uint32_t q_addr[{len(flat)}] = {{\n{body}\n}};\n"
	        "#if Q_NEURONS != WNN_NEURONS\n#error \"query header is for another winner\"\n#endif\n")


def main():
	args = parse_args()
	z = np.load(args.trace)
	rows = decision_rows(z["addr"], z["ep_len"], args.ticks)
	with open(args.out, "w") as f:
		f.write(render(rows, args.trace))
	print(f"wrote {args.out}: {rows.shape[0]} decision ticks x {rows.shape[1]} neurons")


if __name__ == "__main__":
	main()
